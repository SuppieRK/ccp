package agents

import (
	"errors"
	"os"
	"path/filepath"
	"strings"
)

const (
	legacyRuleSignature      = "Use `ccp` as the command prefix for every executable in shell commands"
	legacyHookSignature      = "# generated by ccp init for "
	legacyPluginSignature    = `return segment.slice(0, start) + "ccp "`
	legacyAwarenessSignature = "# CCP Integration"
	legacyJSPluginName       = "ccp-rewrite.js"
	legacyHookName           = "ccp-rewrite.sh"
)

// HasLegacyArtifacts reports whether the tool has a pre-rename managed
// contribution. It prevents startup migration from installing integrations
// that the user never enabled.
func HasLegacyArtifacts(ctx Context, tool string) bool {
	paths := legacyPrimaryArtifactPaths(ctx, NormalizeToolID(tool))
	if len(paths) == 0 {
		paths = legacySecondaryArtifactPaths(ctx, NormalizeToolID(tool))
	}
	for _, path := range paths {
		raw, err := os.ReadFile(path)
		if err == nil && legacyArtifactContent(string(raw)) {
			return true
		}
	}
	return false
}

func legacyPrimaryArtifactPaths(ctx Context, tool string) []string {
	switch tool {
	case string(AgentAmazonQ):
		return []string{ResolveRepoScopedPath(ctx.ScopeRoot, ".amazonq/rules/ccp.md")}
	case string(AgentCline):
		return []string{ResolveRepoScopedPath(ctx.ScopeRoot, ".clinerules/ccp.md")}
	case string(AgentCursor):
		return []string{ResolveRepoScopedPath(ctx.ScopeRoot, ".cursor/rules/ccp.mdc")}
	case string(AgentRooCode):
		return []string{ResolveHomeScopedPath(ctx.HomeDir, ".roo/rules/ccp.md")}
	case string(AgentTrae):
		return []string{ResolveRepoScopedPath(ctx.ScopeRoot, ".trae/rules/ccp.md")}
	case string(AgentWindsurf):
		return []string{ResolveRepoScopedPath(ctx.ScopeRoot, ".windsurf/rules/ccp.md")}
	case string(AgentOpenCode):
		return []string{filepath.Join(managedJSPluginConfigRoot(ctx, "opencode"), "plugins", legacyJSPluginName)}
	case string(AgentKilocode):
		return []string{filepath.Join(managedJSPluginConfigRoot(ctx, "kilocode"), "plugins", legacyJSPluginName)}
	case string(AgentClaude):
		root := claudeRoot(ctx)
		return []string{
			filepath.Join(root, "hooks", legacyHookName),
			filepath.Join(root, "CCP.md"),
			filepath.Join(root, claudeGuideName),
		}
	case string(AgentCodeBuddy):
		return []string{filepath.Join(codebuddyRoot(ctx), "hooks", legacyHookName)}
	default:
		return nil
	}
}

